    public async Task<InstagramContaCadastro> SalvarContaInstagramAsync(
        int? contaId,
        string nomeCadastro,
        string identificadorInstagram,
        string accountIdMeta,
        string? accessTokenMeta,
        string? graphApiBaseUrl,
        string? baseUrlPublica,
        string? horariosFeedTexto,
        string? horariosStoryTexto,
        bool publicacaoAutomaticaAtiva,
        bool definirComoPadrao,
        int? usuarioAcessoId = null,
        CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);

        if (string.IsNullOrWhiteSpace(nomeCadastro))
        {
            throw new ArgumentException("Informe o nome do cadastro (ex.: Loja Principal, Cliente X).");
        }

        if (string.IsNullOrWhiteSpace(identificadorInstagram))
        {
            throw new ArgumentException("Informe para qual Instagram é este cadastro (ex.: @seuinstagram).");
        }

        if (string.IsNullOrWhiteSpace(accountIdMeta))
        {
            throw new ArgumentException("Informe o Instagram Account ID (ID da conta Business/Creator na Meta).");
        }

        var arrobaFormatado = NormalizarArrobaInstagram(identificadorInstagram);
        var horariosFeed = NormalizarHorarios([horariosFeedTexto ?? "09:00, 13:00, 18:00"]);
        if (horariosFeed.Count == 0)
        {
            horariosFeed = ["09:00", "13:00", "18:00"];
        }

        var horariosStory = NormalizarHorarios([horariosStoryTexto ?? "10:00, 19:00"]);
        if (horariosStory.Count == 0)
        {
            horariosStory = ["10:00", "19:00"];
        }

        var urlApi = string.IsNullOrWhiteSpace(graphApiBaseUrl)
            ? "https://graph.facebook.com/v21.0"
            : graphApiBaseUrl.Trim().TrimEnd('/');

        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);

        UsuarioAcesso? usuarioVinculado = null;
        if (usuarioAcessoId is > 0)
        {
            usuarioVinculado = await db.UsuariosAcesso
                .FirstOrDefaultAsync(u => u.Id == usuarioAcessoId.Value, cancellationToken);
        }

        InstagramContaCadastro conta;
        var existemOutrasContas = await db.ContasInstagram.AnyAsync(cancellationToken);

        if (contaId.HasValue && contaId.Value > 0)
        {
            conta = await db.ContasInstagram
                .FirstOrDefaultAsync(c => c.Id == contaId.Value, cancellationToken)
                ?? throw new InvalidOperationException("Cadastro de Instagram não encontrado.");

            conta.UsuarioAcessoId = usuarioVinculado?.Id;
            conta.LoginUsuarioVinculado = usuarioVinculado is not null
                ? $"{usuarioVinculado.NomeExibicao} ({usuarioVinculado.Login})"
                : null;
            conta.NomeCadastro = nomeCadastro.Trim();
            conta.IdentificadorInstagram = arrobaFormatado;
            conta.AccountIdMeta = accountIdMeta.Trim();
            if (!string.IsNullOrWhiteSpace(accessTokenMeta))
            {
                conta.AccessTokenMeta = accessTokenMeta.Trim();
            }
            conta.GraphApiBaseUrl = urlApi;
            if (!string.IsNullOrWhiteSpace(baseUrlPublica))
            {
                conta.BaseUrlPublica = baseUrlPublica.Trim().TrimEnd('/');
            }
            conta.HorariosFeedJson = JsonSerializer.Serialize(horariosFeed);
            conta.HorariosStoryJson = JsonSerializer.Serialize(horariosStory);
            conta.PublicacaoAutomaticaAtiva = publicacaoAutomaticaAtiva;
            conta.AtualizadoEmUtc = DateTimeOffset.UtcNow;
        }
        else
        {
            if (string.IsNullOrWhiteSpace(accessTokenMeta))
            {
                throw new ArgumentException("Informe o Access Token da Meta Graph API para cadastrar este Instagram.");
            }

            conta = new InstagramContaCadastro
            {
                UsuarioAcessoId = usuarioVinculado?.Id,
                LoginUsuarioVinculado = usuarioVinculado is not null
                    ? $"{usuarioVinculado.NomeExibicao} ({usuarioVinculado.Login})"
                    : null,
                NomeCadastro = nomeCadastro.Trim(),
                IdentificadorInstagram = arrobaFormatado,
                AccountIdMeta = accountIdMeta.Trim(),
                AccessTokenMeta = accessTokenMeta.Trim(),
                GraphApiBaseUrl = urlApi,
                BaseUrlPublica = string.IsNullOrWhiteSpace(baseUrlPublica) ? null : baseUrlPublica.Trim().TrimEnd('/'),
                HorariosFeedJson = JsonSerializer.Serialize(horariosFeed),
                HorariosStoryJson = JsonSerializer.Serialize(horariosStory),
                PublicacaoAutomaticaAtiva = publicacaoAutomaticaAtiva,
                Ativo = true,
                Padrao = !existemOutrasContas || definirComoPadrao,
                CriadoEmUtc = DateTimeOffset.UtcNow,
                AtualizadoEmUtc = DateTimeOffset.UtcNow
            };

            db.ContasInstagram.Add(conta);
        }

        await db.SaveChangesAsync(cancellationToken);

        if (usuarioVinculado is not null)
        {
            usuarioVinculado.InstagramContaId = conta.Id;
            usuarioVinculado.IdentificadorInstagramVinculado = conta.IdentificadorInstagram;
            await db.SaveChangesAsync(cancellationToken);
        }

        if (definirComoPadrao || !existemOutrasContas)
        {
            var todas = await db.ContasInstagram.ToListAsync(cancellationToken);
            foreach (var item in todas)
            {
                item.Padrao = item.Id == conta.Id;
            }
            await db.SaveChangesAsync(cancellationToken);
        }

        // Atualiza rótulo nos usuários vinculados a esta conta
        var usuariosVinculados = await db.UsuariosAcesso
            .Where(u => u.InstagramContaId == conta.Id)
            .ToListAsync(cancellationToken);
        foreach (var u in usuariosVinculados)
        {
            u.IdentificadorInstagramVinculado = conta.IdentificadorInstagram;
        }
        await db.SaveChangesAsync(cancellationToken);

        return conta;
    }

    public async Task<ResultadoTesteConexaoMeta> TestarESalvarStatusContaAsync(
        int contaId,
        CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);
        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);

