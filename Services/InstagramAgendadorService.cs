    public async Task<int> ProcessarFilaVencidaAsync(CancellationToken cancellationToken = default)
    {
        if (!await _semaforoPublicacao.WaitAsync(0, cancellationToken))
        {
            return 0;
        }

        try
        {
            await GarantirBancoInicializadoAsync(cancellationToken);
            await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);

            var contasAtivasIds = await db.ContasInstagram
                .AsNoTracking()
                .Where(c => c.Ativo && c.PublicacaoAutomaticaAtiva)
                .Select(c => c.Id)
                .ToListAsync(cancellationToken);

            if (contasAtivasIds.Count == 0)
            {
                return 0;
            }

            var agoraUtc = DateTimeOffset.UtcNow;

            var postsCandidatos = await db.PostsAgendados
                .AsNoTracking()
                .Where(p =>
                    contasAtivasIds.Contains(p.InstagramContaId) &&
                    p.Status == StatusPostInstagram.Agendado)
                .Select(p => new { p.Id, p.HorarioProgramadoUtc })
                .ToListAsync(cancellationToken);

            var postsVencidosIds = postsCandidatos
                .Where(p => p.HorarioProgramadoUtc <= agoraUtc)
                .OrderBy(p => p.HorarioProgramadoUtc)
                .Take(5)
                .Select(p => p.Id)
                .ToList();

            var publicados = 0;
            foreach (var postId in postsVencidosIds)
            {
                cancellationToken.ThrowIfCancellationRequested();
                var (sucesso, _) = await ExecutarPublicacaoPostInternaAsync(postId, null, cancellationToken);
                if (sucesso)
                {
                    publicados++;
                }
            }

            var storiesCandidatos = await db.StoriesRecorrentes
                .AsNoTracking()
                .Where(s =>
                    contasAtivasIds.Contains(s.InstagramContaId) &&
                    s.Ativo)
                .Select(s => new { s.Id, s.ProximoDisparoUtc })
                .ToListAsync(cancellationToken);

            var storiesVencidosIds = storiesCandidatos
                .Where(s => s.ProximoDisparoUtc <= agoraUtc)
                .OrderBy(s => s.ProximoDisparoUtc)
                .Take(5)
                .Select(s => s.Id)
                .ToList();

            foreach (var storyId in storiesVencidosIds)
            {
                cancellationToken.ThrowIfCancellationRequested();
                var (sucessoStory, _) = await ExecutarPublicacaoStoryRecorrenteInternaAsync(
                    storyId,
                    baseUrlPublicaAtual: null,
                    disparoAutomatico: true,
                    cancellationToken);
                if (sucessoStory)
                {
                    publicados++;
                }
            }

            return publicados;
        }
        finally
        {
            _semaforoPublicacao.Release();
        }
    }

    private async Task<(bool Sucesso, string Mensagem)> ExecutarPublicacaoPostInternaAsync(
        int postId,
        string? baseUrlPublicaAtual,
        CancellationToken cancellationToken)
    {
        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);
        var post = await db.PostsAgendados
            .FirstOrDefaultAsync(p => p.Id == postId, cancellationToken);

        if (post is null)
        {
            return (false, "Agendamento não encontrado.");
        }

        var conta = await db.ContasInstagram
            .AsNoTracking()
            .FirstOrDefaultAsync(c => c.Id == post.InstagramContaId, cancellationToken);

        if (conta is null)
        {
            post.Status = StatusPostInstagram.Falha;
            post.UltimoErro = "A conta do Instagram vinculada a este agendamento não foi encontrada.";
            await db.SaveChangesAsync(cancellationToken);
            return (false, post.UltimoErro);
        }

        if (!string.IsNullOrWhiteSpace(baseUrlPublicaAtual))
        {
            post.BaseUrlPublica = baseUrlPublicaAtual.Trim().TrimEnd('/');
        }

        var basePub = post.BaseUrlPublica ?? conta.BaseUrlPublica;
        string? urlImagemParaMeta = post.UrlImagemExterna;

        if (post.ConteudoImagem is { Length: > 0 })
        {
            if (string.IsNullOrWhiteSpace(basePub))
            {
                var msg = "A URL pública do servidor ainda não foi registrada para servir a imagem enviada. Publique pelo painel ou configure a URL pública.";
                post.Status = StatusPostInstagram.Falha;
                post.UltimoErro = msg;
                await db.SaveChangesAsync(cancellationToken);
                return (false, msg);
            }

            urlImagemParaMeta = $"{basePub.TrimEnd('/')}/media/post/{post.Id}.jpg?v={post.CriadoEmUtc.UtcTicks}";
        }

        if (string.IsNullOrWhiteSpace(urlImagemParaMeta))
        {
            post.Status = StatusPostInstagram.Falha;
            post.UltimoErro = "Nenhuma imagem disponível para publicar no Instagram.";
            await db.SaveChangesAsync(cancellationToken);
            return (false, post.UltimoErro);
        }

        post.Status = StatusPostInstagram.Publicando;
        post.Tentativas++;
        await db.SaveChangesAsync(cancellationToken);

        var tipo = NormalizarTipoPublicacao(post.TipoPublicacao);
        var publicarFeed = tipo is TipoMidiaInstagram.Feed or TipoMidiaInstagram.FeedEStories;
        var publicarStory = tipo is TipoMidiaInstagram.Stories or TipoMidiaInstagram.FeedEStories;

        ResultadoPublicacaoMeta? resFeed = null;
        ResultadoPublicacaoMeta? resStory = null;

        if (publicarFeed)
        {
            resFeed = await _graphApi.PublicarFeedImagemAsync(conta, urlImagemParaMeta, post.Legenda, cancellationToken);
        }

        if (publicarStory)
        {
            resStory = await _graphApi.PublicarStoryImagemAsync(conta, urlImagemParaMeta, cancellationToken);
        }

        var peloMenosUmSucesso = (publicarFeed && resFeed?.Sucesso == true) ||
                                 (publicarStory && resStory?.Sucesso == true);

        if (peloMenosUmSucesso)
        {
            post.Status = StatusPostInstagram.Publicado;
            post.CreationIdMeta = resFeed?.CreationId ?? resStory?.CreationId;
            post.MediaIdMeta = resFeed?.MediaId ?? resStory?.MediaId;
            post.PublicadoEmUtc = DateTimeOffset.UtcNow;
            post.UltimoErro = null;
            await db.SaveChangesAsync(cancellationToken);

            return (true, $"Publicado com sucesso em {conta.IdentificadorInstagram} (Media ID: {post.MediaIdMeta}).");
        }

        var erroMsg = resFeed?.Erro ?? resStory?.Erro ?? "Falha desconhecida ao publicar na API do Instagram.";
        post.Status = StatusPostInstagram.Falha;
        post.UltimoErro = erroMsg.Length > 1500 ? erroMsg[..1500] : erroMsg;
        await db.SaveChangesAsync(cancellationToken);

        return (false, erroMsg);
    }

    private async Task<(bool Sucesso, string Mensagem)> ExecutarPublicacaoStoryRecorrenteInternaAsync(
        int storyId,
        string? baseUrlPublicaAtual,
        bool disparoAutomatico,
        CancellationToken cancellationToken)
    {
        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);
        var story = await db.StoriesRecorrentes
            .FirstOrDefaultAsync(s => s.Id == storyId, cancellationToken);

        if (story is null)
        {
            return (false, "Story programado não encontrado.");
        }

        var conta = await db.ContasInstagram
            .AsNoTracking()
            .FirstOrDefaultAsync(c => c.Id == story.InstagramContaId, cancellationToken);

        if (conta is null)
        {
            story.UltimoErro = "Conta do Instagram vinculada não encontrada.";
            await db.SaveChangesAsync(cancellationToken);
            return (false, story.UltimoErro);
        }

        if (!string.IsNullOrWhiteSpace(baseUrlPublicaAtual))
        {
            story.BaseUrlPublica = baseUrlPublicaAtual.Trim().TrimEnd('/');
        }

        var basePub = story.BaseUrlPublica ?? conta.BaseUrlPublica;
        if (string.IsNullOrWhiteSpace(basePub))
        {
            var msg = "URL pública do servidor não definida para servir a arte do Story à Meta.";
            story.UltimoErro = msg;
            await db.SaveChangesAsync(cancellationToken);
            return (false, msg);
        }

        var urlImagemPublica =
            $"{basePub.TrimEnd('/')}/media/story/{story.Id}.jpg?v={story.CriadoEmUtc.UtcTicks}";

        var resultado = await _graphApi.PublicarStoryImagemAsync(conta, urlImagemPublica, cancellationToken);
        var agoraLocal = FusoHorarioService.AgoraLocal.DateTime;
        var agoraUtc = DateTimeOffset.UtcNow;

        if (resultado.Sucesso)
        {
            story.TotalPublicacoes++;
            story.UltimaPublicacaoEmUtc = agoraUtc;
            story.UltimoMediaIdMeta = resultado.MediaId;
            story.UltimoErro = null;
            story.TentativasNoHorarioAtual = 0;

            if (story.ModoAgendamento == ModoStoryRecorrente.RecorrenteDiario)
            {
                var horarios = DeserializarHorarios(story.HorariosDiariosJson, ["10:00", "19:00"]);
                var dias = DeserializarDiasSemana(story.DiasSemanaJson);
                story.ProximoDisparoLocal = CalcularProximoHorarioDiarioLocal(
                    horarios,
                    agoraLocal.AddMinutes(1),
                    dias);
                story.ProximoDisparoUtc = FusoHorarioService.ConverterParaUtc(story.ProximoDisparoLocal);
                story.Ativo = true;
                story.Status = StatusStoryRecorrente.Ativo;
            }
            else if (disparoAutomatico)
            {
                story.Ativo = false;
                story.Status = StatusStoryRecorrente.Concluido;
            }

            await db.SaveChangesAsync(cancellationToken);
            return (true, $"Story '{story.Titulo}' publicado com sucesso em {conta.IdentificadorInstagram} (Media ID: {resultado.MediaId}).");
        }

        var erroMsg = resultado.Erro ?? "Erro ao publicar Story no Instagram.";
        story.TentativasNoHorarioAtual++;
        story.UltimoErro = erroMsg.Length > 1500 ? erroMsg[..1500] : erroMsg;

        if (disparoAutomatico)
        {
            if (story.TentativasNoHorarioAtual >= 3)
            {
                if (story.ModoAgendamento == ModoStoryRecorrente.RecorrenteDiario)
                {
                    var horarios = DeserializarHorarios(story.HorariosDiariosJson, ["10:00", "19:00"]);
                    var dias = DeserializarDiasSemana(story.DiasSemanaJson);
                    story.ProximoDisparoLocal = CalcularProximoHorarioDiarioLocal(
                        horarios,
                        agoraLocal.AddMinutes(2),
                        dias);
                    story.ProximoDisparoUtc = FusoHorarioService.ConverterParaUtc(story.ProximoDisparoLocal);
                    story.TentativasNoHorarioAtual = 0;
                }
                else
                {
                    story.Ativo = false;
                    story.Status = StatusStoryRecorrente.Falha;
                }
            }
            else
            {
                story.ProximoDisparoUtc = agoraUtc.AddMinutes(5);
            }
        }

        await db.SaveChangesAsync(cancellationToken);
        return (false, erroMsg);
    }

