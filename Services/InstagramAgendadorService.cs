    public async Task<IReadOnlyList<DateTime>> CalcularProximosHorariosFeedAsync(
        int instagramContaId,
        int quantidade = 15,
        CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);
        if (quantidade <= 0)
        {
            return [];
        }

        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);
        var conta = await db.ContasInstagram
            .AsNoTracking()
            .FirstOrDefaultAsync(c => c.Id == instagramContaId, cancellationToken);

        var horariosTexto = DeserializarHorarios(conta?.HorariosFeedJson, ["09:00", "13:00", "18:00"]);
        var horariosTimeOnly = horariosTexto
            .Select(h => TimeOnly.TryParseExact(h, "HH:mm", CultureInfo.InvariantCulture, DateTimeStyles.None, out var t) ? (TimeOnly?)t : null)
            .Where(t => t.HasValue)
            .Select(t => t!.Value)
            .OrderBy(t => t)
            .ToArray();

        if (horariosTimeOnly.Length == 0)
        {
            horariosTimeOnly = [new TimeOnly(9, 0), new TimeOnly(13, 0), new TimeOnly(18, 0)];
        }

        var agoraLocal = FusoHorarioService.AgoraLocal.DateTime;
        var agoraUtc = DateTimeOffset.UtcNow;

        var postsAtivos = await db.PostsAgendados
            .AsNoTracking()
            .Where(p =>
                p.InstagramContaId == instagramContaId &&
                (p.Status == StatusPostInstagram.Agendado ||
                 p.Status == StatusPostInstagram.Publicando ||
                 p.Status == StatusPostInstagram.Publicado))
            .Select(p => p.HorarioProgramadoUtc)
            .ToListAsync(cancellationToken);

        var ocupadosUtc = postsAtivos
            .Where(h => h >= agoraUtc.AddMinutes(-10))
            .ToList();

        var slotsEscolhidos = new List<DateTime>(quantidade);
        var dataCursor = DateOnly.FromDateTime(agoraLocal);

        while (slotsEscolhidos.Count < quantidade)
        {
            foreach (var hora in horariosTimeOnly)
            {
                var candidatoLocal = DateTime.SpecifyKind(
                    dataCursor.ToDateTime(hora),
                    DateTimeKind.Unspecified);

                if (candidatoLocal <= agoraLocal.AddMinutes(2))
                {
                    continue;
                }

                var candidatoUtc = FusoHorarioService.ConverterParaUtc(candidatoLocal);
                var jaOcupado = ocupadosUtc.Any(ocupado =>
                    Math.Abs((ocupado - candidatoUtc).TotalMinutes) < 5);

                if (jaOcupado)
                {
                    continue;
                }

                slotsEscolhidos.Add(candidatoLocal);
                ocupadosUtc.Add(candidatoUtc);

                if (slotsEscolhidos.Count >= quantidade)
                {
                    break;
                }
            }

            dataCursor = dataCursor.AddDays(1);
        }

        return slotsEscolhidos;
    }

    public async Task<InstagramPostAgendado> CriarPostAgendadoAsync(
        int instagramContaId,
        string titulo,
        string legenda,
        string tipoPublicacao,
        byte[]? conteudoImagem,
        string? contentTypeImagem,
        string? urlImagemExterna,
        DateTime? horarioEscolhidoLocal,
        string baseUrlPublica,
        CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);

        if ((conteudoImagem is null || conteudoImagem.Length == 0) &&
            string.IsNullOrWhiteSpace(urlImagemExterna))
        {
            throw new ArgumentException("Envie uma imagem do seu celular/computador ou informe uma URL pública de imagem.");
        }

        if (conteudoImagem is { Length: > 8 * 1024 * 1024 })
        {
            throw new ArgumentException("A imagem enviada deve ter no máximo 8 MB.");
        }

        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);
        var conta = await db.ContasInstagram
            .FirstOrDefaultAsync(c => c.Id == instagramContaId, cancellationToken)
            ?? throw new InvalidOperationException("Selecione um cadastro de Instagram válido antes de agendar.");

        if (!string.IsNullOrWhiteSpace(baseUrlPublica))
        {
            conta.BaseUrlPublica = baseUrlPublica.Trim().TrimEnd('/');
        }

        DateTime horarioLocal;
        if (horarioEscolhidoLocal.HasValue)
        {
            horarioLocal = DateTime.SpecifyKind(horarioEscolhidoLocal.Value, DateTimeKind.Unspecified);
        }
        else
        {
            var proximos = await CalcularProximosHorariosFeedAsync(instagramContaId, 1, cancellationToken);
            horarioLocal = proximos.Count > 0
                ? proximos[0]
                : FusoHorarioService.AgoraLocal.DateTime.AddHours(1);
        }

        var legendaLimpa = (legenda ?? string.Empty).Trim();
        if (legendaLimpa.Length > 2200)
        {
            legendaLimpa = legendaLimpa[..2200];
        }

        var post = new InstagramPostAgendado
        {
            InstagramContaId = conta.Id,
            IdentificadorInstagram = conta.IdentificadorInstagram,
            Titulo = string.IsNullOrWhiteSpace(titulo) ? "Publicação Instagram" : titulo.Trim(),
            Legenda = legendaLimpa,
            TipoPublicacao = NormalizarTipoPublicacao(tipoPublicacao),
            ConteudoImagem = conteudoImagem is { Length: > 0 } ? conteudoImagem : null,
            ContentTypeImagem = string.IsNullOrWhiteSpace(contentTypeImagem) ? "image/jpeg" : contentTypeImagem.Trim(),
            UrlImagemExterna = string.IsNullOrWhiteSpace(urlImagemExterna) ? null : urlImagemExterna.Trim(),
            BaseUrlPublica = baseUrlPublica?.Trim().TrimEnd('/'),
            HorarioProgramadoLocal = horarioLocal,
            HorarioProgramadoUtc = FusoHorarioService.ConverterParaUtc(horarioLocal),
            Status = StatusPostInstagram.Agendado,
            CriadoEmUtc = DateTimeOffset.UtcNow
        };

        db.PostsAgendados.Add(post);
        await db.SaveChangesAsync(cancellationToken);

        return post;
    }

