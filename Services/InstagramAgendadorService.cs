using Microsoft.EntityFrameworkCore;

namespace InstagramAgendador.Web.Services;

public sealed class InstagramAgendadorService
{
    private readonly IDbContextFactory<AgendadorDbContext> _dbFactory;
    private readonly InstagramGraphApiService _graphApi;
    private readonly IConfiguration _configuration;
    private readonly ILogger<InstagramAgendadorService> _logger;
    private readonly SemaphoreSlim _semaforoPublicacao = new(1, 1);
    private readonly SemaphoreSlim _semaforoInit = new(1, 1);
    private bool _bancoInicializado;

    public InstagramAgendadorService(
        IDbContextFactory<AgendadorDbContext> dbFactory,
        InstagramGraphApiService graphApi,
        IConfiguration configuration,
        ILogger<InstagramAgendadorService> logger)
    {
        _dbFactory = dbFactory;
        _graphApi = graphApi;
        _configuration = configuration;
        _logger = logger;
    }

    public async Task GarantirBancoInicializadoAsync(CancellationToken cancellationToken = default)
    {
        if (_bancoInicializado)
        {
            return;
        }

        await _semaforoInit.WaitAsync(cancellationToken);
        try
        {
            if (_bancoInicializado)
            {
                return;
            }

            await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);
            if (db.Database.ProviderName?.Contains("Sqlite", StringComparison.OrdinalIgnoreCase) == true)
            {
                await db.Database.EnsureCreatedAsync(cancellationToken);

                try
                {
                    await db.Database.ExecuteSqlRawAsync(
                        """ALTER TABLE "IgSistema_ContasInstagram" ADD COLUMN "UsuarioAcessoId" INTEGER NULL;""",
                        cancellationToken);
                }
                catch
                {
                    // Coluna já existe
                }

                try
                {
                    await db.Database.ExecuteSqlRawAsync(
                        """ALTER TABLE "IgSistema_ContasInstagram" ADD COLUMN "LoginUsuarioVinculado" TEXT NULL;""",
                        cancellationToken);
                }
                catch
                {
                    // Coluna já existe
                }

                try
                {
                    await db.Database.ExecuteSqlRawAsync(
                        """ALTER TABLE "IgSistema_ContasInstagram" ADD COLUMN "DiasSemanaJson" TEXT NOT NULL DEFAULT '[0,1,2,3,4,5,6]';""",
                        cancellationToken);
                }
                catch
                {
                    // Coluna já existe
                }

                try
                {
                    await db.Database.ExecuteSqlRawAsync(
                        """ALTER TABLE "IgSistema_StoriesRecorrentes" ADD COLUMN "DiasSemanaJson" TEXT NOT NULL DEFAULT '[0,1,2,3,4,5,6]';""",
                        cancellationToken);
                }
                catch
                {
                    // Coluna já existe
                }
            }
            else
            {
                await db.Database.ExecuteSqlRawAsync(
                    """
                    CREATE TABLE IF NOT EXISTS "DataProtectionKeys" (
                        "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        "FriendlyName" text NULL,
                        "Xml" text NULL
                    );

                    CREATE TABLE IF NOT EXISTS "IgSistema_ContasInstagram" (
                        "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        "UsuarioAcessoId" integer NULL,
                        "LoginUsuarioVinculado" character varying(250) NULL,
                        "NomeCadastro" character varying(120) NOT NULL,
                        "IdentificadorInstagram" character varying(100) NOT NULL,
                        "AccountIdMeta" character varying(120) NOT NULL,
                        "AccessTokenMeta" text NOT NULL,
                        "GraphApiBaseUrl" character varying(250) NOT NULL DEFAULT 'https://graph.facebook.com/v21.0',
                        "BaseUrlPublica" character varying(500) NULL,
                        "HorariosFeedJson" character varying(500) NOT NULL DEFAULT '["09:00","13:00","18:00"]',
                        "HorariosStoryJson" character varying(500) NOT NULL DEFAULT '["10:00","19:00"]',
                        "DiasSemanaJson" character varying(150) NOT NULL DEFAULT '[0,1,2,3,4,5,6]',
                        "PublicacaoAutomaticaAtiva" boolean NOT NULL DEFAULT TRUE,
                        "Ativo" boolean NOT NULL DEFAULT TRUE,
                        "Padrao" boolean NOT NULL DEFAULT FALSE,
                        "UltimoTesteStatus" character varying(500) NULL,
                        "UltimoTesteEmUtc" timestamp with time zone NULL,
                        "CriadoEmUtc" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        "AtualizadoEmUtc" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
                    );

                    ALTER TABLE "IgSistema_ContasInstagram"
                        ADD COLUMN IF NOT EXISTS "UsuarioAcessoId" integer NULL;
                    ALTER TABLE "IgSistema_ContasInstagram"
                        ADD COLUMN IF NOT EXISTS "LoginUsuarioVinculado" character varying(250) NULL;
                    ALTER TABLE "IgSistema_ContasInstagram"
                        ADD COLUMN IF NOT EXISTS "DiasSemanaJson" character varying(150) NOT NULL DEFAULT '[0,1,2,3,4,5,6]';
                    ALTER TABLE "IgSistema_ContasInstagram"
                        ALTER COLUMN "LoginUsuarioVinculado" TYPE character varying(250);
                    ALTER TABLE "IgSistema_ContasInstagram"
                        ALTER COLUMN "AccessTokenMeta" TYPE text;
                    ALTER TABLE "IgSistema_ContasInstagram"
                        ALTER COLUMN "UltimoTesteStatus" TYPE text;

                    CREATE TABLE IF NOT EXISTS "IgSistema_UsuariosAcesso" (
                        "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        "NomeExibicao" character varying(120) NOT NULL,
                        "Login" character varying(80) NOT NULL UNIQUE,
                        "SenhaHash" character varying(400) NOT NULL,
                        "InstagramContaId" integer NULL,
                        "IdentificadorInstagramVinculado" character varying(120) NULL,
                        "Administrador" boolean NOT NULL DEFAULT TRUE,
                        "Ativo" boolean NOT NULL DEFAULT TRUE,
                        "CriadoEmUtc" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
                    );

                    CREATE TABLE IF NOT EXISTS "IgSistema_PostsAgendados" (
                        "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        "InstagramContaId" integer NOT NULL,
                        "IdentificadorInstagram" character varying(100) NOT NULL,
                        "Titulo" character varying(180) NOT NULL,
                        "Legenda" character varying(2200) NOT NULL,
                        "TipoPublicacao" character varying(30) NOT NULL DEFAULT 'Feed',
                        "ConteudoImagem" bytea NULL,
                        "ContentTypeImagem" character varying(80) NULL,
                        "UrlImagemExterna" character varying(1000) NULL,
                        "BaseUrlPublica" character varying(500) NULL,
                        "HorarioProgramadoLocal" timestamp without time zone NOT NULL,
                        "HorarioProgramadoUtc" timestamp with time zone NOT NULL,
                        "Status" character varying(30) NOT NULL,
                        "CreationIdMeta" character varying(120) NULL,
                        "MediaIdMeta" character varying(120) NULL,
                        "Tentativas" integer NOT NULL DEFAULT 0,
                        "UltimoErro" character varying(1500) NULL,
