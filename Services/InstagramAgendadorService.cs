                    ALTER TABLE "IgSistema_StoriesRecorrentes"
                        ADD COLUMN IF NOT EXISTS "DiasSemanaJson" character varying(150) NOT NULL DEFAULT '[0,1,2,3,4,5,6]';

                    CREATE INDEX IF NOT EXISTS "IX_IgSistema_StoriesRecorrentes_Fila"
                        ON "IgSistema_StoriesRecorrentes" ("InstagramContaId", "Ativo", "ProximoDisparoUtc");
                    """,
                    cancellationToken);
            }

            // Se houver credenciais de ambiente e nenhuma conta cadastrada ainda, importa automaticamente como primeira conta
            if (!await db.ContasInstagram.AnyAsync(cancellationToken))
            {
                var envAccountId = (_configuration["Instagram:AccountId"]
                    ?? Environment.GetEnvironmentVariable("INSTAGRAM__ACCOUNTID")
                    ?? string.Empty).Trim();
                var envToken = (_configuration["Instagram:AccessToken"]
                    ?? Environment.GetEnvironmentVariable("INSTAGRAM__ACCESSTOKEN")
                    ?? string.Empty).Trim();

                if (!string.IsNullOrWhiteSpace(envAccountId) && !string.IsNullOrWhiteSpace(envToken))
                {
                    db.ContasInstagram.Add(new InstagramContaCadastro
                    {
                        NomeCadastro = "Conta Principal (Importada)",
                        IdentificadorInstagram = "@instagram_principal",
                        AccountIdMeta = envAccountId,
                        AccessTokenMeta = envToken,
                        Padrao = true,
                        Ativo = true
                    });
                    await db.SaveChangesAsync(cancellationToken);
                }
            }

            // Garante que sempre exista pelo menos o Administrador inicial no banco
            if (!await db.UsuariosAcesso.AnyAsync(cancellationToken))
            {
                var envUser = (_configuration["Authentication:Username"] ?? string.Empty).Trim();
                var envPass = _configuration["Authentication:Password"] ?? string.Empty;

                var loginAdmin = string.IsNullOrWhiteSpace(envUser) ? "admin" : envUser.ToLowerInvariant();
                var senhaAdmin = string.IsNullOrEmpty(envPass) ? "admin123" : envPass;

                var primeiraConta = await db.ContasInstagram.AsNoTracking().FirstOrDefaultAsync(cancellationToken);
                db.UsuariosAcesso.Add(new UsuarioAcesso
                {
                    NomeExibicao = "Administrador Geral",
                    Login = loginAdmin,
                    SenhaHash = SenhaService.GerarHash(senhaAdmin),
                    InstagramContaId = primeiraConta?.Id,
                    IdentificadorInstagramVinculado = primeiraConta?.IdentificadorInstagram,
                    Administrador = true,
                    Ativo = true
                });
                await db.SaveChangesAsync(cancellationToken);
            }

            _bancoInicializado = true;
        }
        finally
        {
            _semaforoInit.Release();
        }
    }

