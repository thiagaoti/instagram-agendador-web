    public async Task<bool> ExisteAlgumUsuarioAsync(CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);
        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);
        return await db.UsuariosAcesso.AnyAsync(cancellationToken);
    }

    public async Task<IReadOnlyList<UsuarioAcesso>> ListarUsuariosAsync(CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);
        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);
        return await db.UsuariosAcesso
            .AsNoTracking()
            .OrderBy(u => u.NomeExibicao)
            .ToListAsync(cancellationToken);
    }

    public async Task<UsuarioAcesso?> AutenticarUsuarioAsync(
        string login,
        string senha,
        CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);
        if (string.IsNullOrWhiteSpace(login) || string.IsNullOrEmpty(senha))
        {
            return null;
        }

        var loginNormalizado = login.Trim().ToLowerInvariant();
        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);

        var usuario = await db.UsuariosAcesso
            .AsNoTracking()
            .FirstOrDefaultAsync(
                u => u.Ativo && u.Login.ToLower() == loginNormalizado,
                cancellationToken);

        if (usuario is not null && SenhaService.VerificarSenha(senha, usuario.SenhaHash))
        {
            return usuario;
        }

        return null;
    }

    public async Task<UsuarioAcesso> SalvarUsuarioAcessoAsync(
        int? usuarioId,
        string nomeExibicao,
        string login,
        string? senha,
        int? instagramContaId,
        bool administrador = true,
        CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);

        if (string.IsNullOrWhiteSpace(nomeExibicao))
        {
            throw new ArgumentException("Informe o nome do cadastro/usuário.");
        }

        if (string.IsNullOrWhiteSpace(login))
        {
            throw new ArgumentException("Informe o usuário (login) de acesso.");
        }

        var loginLimpo = login.Trim().ToLowerInvariant();

        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);

        var duplicado = await db.UsuariosAcesso
            .AnyAsync(u => u.Login.ToLower() == loginLimpo && (!usuarioId.HasValue || u.Id != usuarioId.Value), cancellationToken);

        if (duplicado)
        {
            throw new InvalidOperationException($"Já existe um cadastro utilizando o login '{loginLimpo}'.");
        }

        string? identificadorIg = null;
        if (instagramContaId.HasValue && instagramContaId.Value > 0)
        {
            var conta = await db.ContasInstagram
                .AsNoTracking()
                .FirstOrDefaultAsync(c => c.Id == instagramContaId.Value, cancellationToken);
            identificadorIg = conta?.IdentificadorInstagram;
            if (conta is null)
            {
                instagramContaId = null;
            }
        }
        else
        {
            instagramContaId = null;
        }

        UsuarioAcesso registro;
        if (usuarioId.HasValue && usuarioId.Value > 0)
        {
            registro = await db.UsuariosAcesso
                .FirstOrDefaultAsync(u => u.Id == usuarioId.Value, cancellationToken)
                ?? throw new InvalidOperationException("Usuário não encontrado.");

            registro.NomeExibicao = nomeExibicao.Trim();
            registro.Login = loginLimpo;
            registro.InstagramContaId = instagramContaId;
            registro.IdentificadorInstagramVinculado = identificadorIg;
            registro.Administrador = administrador;

            if (!string.IsNullOrWhiteSpace(senha))
            {
                if (senha.Trim().Length < 4)
                {
                    throw new ArgumentException("A senha deve ter pelo menos 4 caracteres.");
                }
                registro.SenhaHash = SenhaService.GerarHash(senha.Trim());
            }
        }
        else
        {
            if (string.IsNullOrWhiteSpace(senha) || senha.Trim().Length < 4)
            {
                throw new ArgumentException("Informe uma senha com pelo menos 4 caracteres para o novo cadastro.");
            }

            registro = new UsuarioAcesso
            {
                NomeExibicao = nomeExibicao.Trim(),
                Login = loginLimpo,
                SenhaHash = SenhaService.GerarHash(senha.Trim()),
                InstagramContaId = instagramContaId,
                IdentificadorInstagramVinculado = identificadorIg,
                Administrador = administrador,
                Ativo = true,
                CriadoEmUtc = DateTimeOffset.UtcNow
            };

            db.UsuariosAcesso.Add(registro);
        }

        await db.SaveChangesAsync(cancellationToken);

        if (instagramContaId.HasValue && instagramContaId.Value > 0)
        {
            var contaAlvo = await db.ContasInstagram
                .FirstOrDefaultAsync(c => c.Id == instagramContaId.Value, cancellationToken);
            if (contaAlvo is not null)
            {
                contaAlvo.UsuarioAcessoId = registro.Id;
                contaAlvo.LoginUsuarioVinculado = $"{registro.NomeExibicao} ({registro.Login})";
                await db.SaveChangesAsync(cancellationToken);
            }
        }

        return registro;
    }

    public async Task ExcluirUsuarioAsync(int usuarioId, CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);
        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);

        var totalUsuarios = await db.UsuariosAcesso.CountAsync(cancellationToken);
        if (totalUsuarios <= 1)
        {
            throw new InvalidOperationException("Não é possível excluir o único usuário cadastrado no sistema.");
        }

        var usuario = await db.UsuariosAcesso.FirstOrDefaultAsync(u => u.Id == usuarioId, cancellationToken);
        if (usuario is not null)
        {
            db.UsuariosAcesso.Remove(usuario);
            await db.SaveChangesAsync(cancellationToken);
        }
    }

