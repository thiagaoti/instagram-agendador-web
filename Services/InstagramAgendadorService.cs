    public async Task<IReadOnlyList<InstagramContaCadastro>> ListarContasAsync(
        CancellationToken cancellationToken = default)
    {
        await GarantirBancoInicializadoAsync(cancellationToken);
        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);
        return await db.ContasInstagram
            .AsNoTracking()
            .OrderByDescending(c => c.Padrao)
            .ThenByDescending(c => c.Ativo)
            .ThenBy(c => c.NomeCadastro)
            .ToListAsync(cancellationToken);
    }

    public async Task<IReadOnlyList<InstagramContaCadastro>> ListarContasParaUsuarioAsync(
        int usuarioId,
        bool ehAdmin,
        CancellationToken cancellationToken = default)
    {
        var todas = await ListarContasAsync(cancellationToken);
        if (ehAdmin)
        {
            return todas;
        }

        await using var db = await _dbFactory.CreateDbContextAsync(cancellationToken);
        var usuario = await db.UsuariosAcesso
            .AsNoTracking()
            .FirstOrDefaultAsync(u => u.Id == usuarioId, cancellationToken);

        var contaPrincipalId = usuario?.InstagramContaId;

        return todas
            .Where(c =>
                c.Ativo &&
                (c.UsuarioAcessoId == usuarioId ||
                 (contaPrincipalId.HasValue && c.Id == contaPrincipalId.Value)))
            .ToList();
    }

